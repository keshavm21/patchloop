"""A results folder as Markdown tables plus a success@k plot. Every number comes from
records.jsonl in that folder; nothing is estimated."""

from pathlib import Path

from .metrics import ConfigMetrics, by_config
from .runner import read_records
from .stats import paired_comparison, repair_rate_ci

# The comparisons §8.4 asks about, (a, b) meaning "does b beat a?"; shown when both ran.
COMPARISONS = [
    ("single_shot", "full"),
    ("binary", "full"),
    ("errors", "full"),
    ("single_shot", "binary"),
    ("full", "full_reflect"),
]

BREAKDOWN_TITLES = {
    "bug_type": "By bug type",
    "failure_symptoms": "By failure symptom",
    "operator": "By mutation operator",
    "symptom": "By failure symptom",
}


def write_report(out: Path) -> Path:
    records = read_records(out)
    if not records:
        raise FileNotFoundError(f"no records in {out}")
    metrics = by_config(records)
    plot = _plot_success_at_k(metrics, out / "success_at_k.png")
    lines = _markdown(records, metrics, plot)
    path = out / "report.md"
    path.write_text("\n".join(lines) + "\n")
    return path


def _markdown(
    records: list[dict], metrics: dict[str, ConfigMetrics], plot: Path | None
) -> list[str]:
    first = records[0]
    prov = first["provenance"]
    lines = [
        f"# {first['bench']} ({first['split']} split)",
        "",
        f"Model `{prov['model']}` at temperature {prov['temperature']}, prompts "
        f"`{prov['prompt_version']}`, git `{prov['git_sha'][:10]}`"
        + (" (with uncommitted changes)" if prov["git_dirty"] else "")
        + f", sandbox image `{(prov['image_id'] or 'unknown')[7:19]}`, dataset checksum "
        f"`{prov['dataset_checksum'][:12]}`, {prov['arch']}.",
        "",
        "Generated by `patchloop report` from `records.jsonl`. Infra errors are excluded from "
        "every rate below and counted separately. Configs whose first prompt is identical (at "
        "temperature 0) share attempt 1 through the response cache, which pairs them; cached "
        "calls keep their recorded tokens but take no time, so compare times with that in mind.",
        "",
        "## Results",
        "",
        "Repair % is the mean over tasks of each task's solve rate across its repeats, with a "
        "95% bootstrap interval over tasks.",
        "",
        "| Config | Tasks × repeats | Repair % [95% CI] | Overfit % | Attempts to success | "
        "Tokens / task | Cost / task | Time / task | Model time / task | Rate-limit wait / task "
        "| Cached calls |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for m in metrics.values():
        cost = f"${m.cost_per_task:.4f}" if m.cost_per_task is not None else "unknown"
        attempts = f"{m.attempts_to_success:.2f}" if m.attempts_to_success is not None else "–"
        ci = repair_rate_ci(records, m.config)
        repair = f"{_pct(ci.mean)} [{_pct(ci.low)}, {_pct(ci.high)}]" if ci else "–"
        lines.append(
            f"| `{m.config}` | {m.tasks} × {m.repeats} | {repair} | "
            f"{_pct(m.overfit_rate)} | {attempts} | {m.tokens_per_task:,.0f} | {cost} | "
            f"{m.seconds_per_task:.1f} s | {m.model_seconds_per_task:.1f} s | "
            f"{m.retry_wait_per_task:.1f} s | {_pct(m.cached_call_share)}% |"
        )
    comparisons = [
        c
        for a, b in COMPARISONS
        if a in metrics and b in metrics
        if (c := paired_comparison(records, a, b))
    ]
    if comparisons:
        lines += [
            "",
            "## Comparisons",
            "",
            "Paired over the tasks both configs finished: the difference in per-task solve rate "
            "(b − a, in points) with a 95% bootstrap interval. An interval that includes zero is "
            "reported as no clear difference.",
            "",
            "| a | b | Tasks | b − a [95% CI] | Verdict |",
            "|---|---|---|---|---|",
        ]
        for c in comparisons:
            d = c.diff
            lines.append(
                f"| `{c.a}` | `{c.b}` | {c.tasks} | {100 * d.mean:+.1f} "
                f"[{100 * d.low:+.1f}, {100 * d.high:+.1f}] | {c.verdict} |"
            )
    max_k = max(m.max_attempts for m in metrics.values())
    lines += [
        "",
        "## Success@k",
        "",
        "Share of runs whose hidden tests pass with the code from attempt k or earlier.",
        "",
        "| Config | " + " | ".join(f"k={k}" for k in range(1, max_k + 1)) + " |",
        "|---|" + "---|" * max_k,
    ]
    for m in metrics.values():
        cells = [
            _pct(m.success_at_k[k]) if k in m.success_at_k else "–" for k in range(1, max_k + 1)
        ]
        lines.append(f"| `{m.config}` | " + " | ".join(cells) + " |")
    if plot:
        lines += ["", f"![success@k]({plot.name})"]

    lines += ["", "## Stop reasons", "", "| Config | " + "Reasons |", "|---|---|"]
    for m in metrics.values():
        reasons = ", ".join(f"{r} {n}" for r, n in m.stop_reasons.items())
        lines.append(f"| `{m.config}` | {reasons} |")

    lines += [
        "",
        "## Regressions, cut-off replies and sandbox time",
        "",
        "A cut-off reply hit the config's `max_output_tokens` (for a reasoning model, often "
        "while still thinking) and usually ends as PARSE_FAILED.",
        "",
        "| Config | Regression % | Cut-off replies % | Sandbox p50 | Sandbox p95 |",
        "|---|---|---|---|---|",
    ]
    for m in metrics.values():
        reg = _pct(m.regression_rate) if m.regression_rate is not None else "– (no second attempts)"
        p50 = f"{m.sandbox_p50_s:.2f} s" if m.sandbox_p50_s is not None else "–"
        p95 = f"{m.sandbox_p95_s:.2f} s" if m.sandbox_p95_s is not None else "–"
        cut = _pct(m.cut_off_rate) if m.cut_off_rate is not None else "not recorded"
        lines.append(f"| `{m.config}` | {reg} | {cut} | {p50} | {p95} |")

    keys = [k for k in BREAKDOWN_TITLES if any(k in m.breakdowns for m in metrics.values())]
    for key in keys:
        values = sorted({v for m in metrics.values() for v in m.breakdowns.get(key, {})})
        names = list(metrics)
        lines += [
            "",
            f"## {BREAKDOWN_TITLES[key]}",
            "",
            "| "
            + key.replace("_", " ").capitalize()
            + " | Runs | "
            + " | ".join(f"`{n}`" for n in names)
            + " |",
            "|---|---|" + "---|" * len(names),
        ]
        for v in values:
            runs = max(metrics[n].breakdowns.get(key, {}).get(v, (0, 0))[0] for n in names)
            cells = [
                _pct(metrics[n].breakdowns[key][v][1])
                if v in metrics[n].breakdowns.get(key, {})
                else "–"
                for n in names
            ]
            lines.append(f"| {v} | {runs} | " + " | ".join(cells) + " |")

    lines += [
        "",
        "## Infra errors",
        "",
        "| Config | Retried, then finished | Quarantined |",
        "|---|---|---|",
    ]
    for m in metrics.values():
        lines.append(f"| `{m.config}` | {m.infra_retried} | {m.quarantined} |")
    return lines


def _plot_success_at_k(metrics: dict[str, ConfigMetrics], path: Path) -> Path | None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    if not any(m.success_at_k for m in metrics.values()):
        return None
    fig, ax = plt.subplots(figsize=(5, 3.2), dpi=150)
    for m in metrics.values():
        ks = sorted(m.success_at_k)
        ax.plot(ks, [100 * m.success_at_k[k] for k in ks], marker="o", label=m.config)
    max_k = max(max(m.success_at_k, default=1) for m in metrics.values())
    ax.set_xticks(range(1, max_k + 1))
    ax.set_xlabel("attempts (k)")
    ax.set_ylabel("solved within k (%)")
    ax.set_ylim(0, 100)
    ax.grid(alpha=0.3)
    ax.legend(frameon=False)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)
    return path


def _pct(x: float) -> str:
    return f"{100 * x:.1f}"
